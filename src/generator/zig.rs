use super::common::{
    Leaf, env_name_literal, format_scalar_literal, has_env_refs, is_valid_identifier, leaf_of,
    single_kind,
};
use super::tree::{ConfigNode, build_config_tree};
use crate::error::Result;
use crate::model::{ResolvedSetting, TypeShape, ValueKind};
use indexmap::IndexMap;
use toml::Value as TomlValue;

pub fn generate_zig(settings: &[ResolvedSetting]) -> Result<String> {
    let tree = build_config_tree(settings, false);
    let mut out = String::from("// Generated by SettingSpec\n\n");
    if has_env_refs(settings) {
        out.push_str("const std = @import(\"std\");\n\n");
    }
    format_zig_scope(&tree, 0, &mut out);
    Ok(out)
}

fn format_zig_scope(map: &IndexMap<String, ConfigNode>, indent_level: usize, out: &mut String) {
    let indent = "    ".repeat(indent_level);

    // Leaf/scalar constants first
    for (k, node) in map {
        match node {
            ConfigNode::Typed(shape, inner) => {
                format_zig_typed(&sanitize_zig_identifier(k), shape, inner, &indent, out);
            }
            ConfigNode::Null | ConfigNode::Env(_) => {
                unreachable!("nulls and environment references are always typed")
            }
            ConfigNode::Value(v) => match v {
                TomlValue::Table(_) => {} // Handled in struct loop below
                _ => {
                    let val_str = toml_to_zig_literal(v);
                    out.push_str(&format!(
                        "{}pub const {} = {};\n",
                        indent,
                        sanitize_zig_identifier(k),
                        val_str
                    ));
                }
            },
            ConfigNode::Map(_) => {}
        }
    }

    // Nested structs next
    for (k, node) in map {
        match node {
            ConfigNode::Map(sub_map) => {
                if !out.ends_with("\n\n") && !out.ends_with("{\n") {
                    out.push('\n');
                }
                out.push_str(&format!(
                    "{}pub const {} = struct {{\n",
                    indent,
                    sanitize_zig_identifier(k)
                ));
                format_zig_scope(sub_map, indent_level + 1, out);
                out.push_str(&format!("{}}};\n", indent));
            }
            ConfigNode::Value(TomlValue::Table(tbl)) => {
                if !out.ends_with("\n\n") && !out.ends_with("{\n") {
                    out.push('\n');
                }
                out.push_str(&format!(
                    "{}pub const {} = struct {{\n",
                    indent,
                    sanitize_zig_identifier(k)
                ));
                let mut sub_map = IndexMap::new();
                for (sub_k, sub_v) in tbl {
                    sub_map.insert(sub_k.clone(), ConfigNode::Value(sub_v.clone()));
                }
                format_zig_scope(&sub_map, indent_level + 1, out);
                out.push_str(&format!("{}}};\n", indent));
            }
            _ => {}
        }
    }
}

fn zig_kind_type(kind: ValueKind) -> &'static str {
    match kind {
        ValueKind::String => "[]const u8",
        ValueKind::Integer => "i64",
        ValueKind::Float => "f64",
        ValueKind::Boolean => "bool",
        ValueKind::Array | ValueKind::Table => unreachable!("rejected before formatting"),
    }
}

/// Zig field name of a kind in a generated tagged union.
fn zig_kind_field(kind: ValueKind) -> &'static str {
    match kind {
        ValueKind::String => "str",
        ValueKind::Integer => "int",
        ValueKind::Float => "float",
        ValueKind::Boolean => "boolean",
        ValueKind::Array | ValueKind::Table => unreachable!("rejected before formatting"),
    }
}

/// Emits a setting whose type is shared by all profiles: an optional constant
/// for a single kind, a function if it reads the environment, or a tagged
/// union (and a function returning it) for several kinds.
fn format_zig_typed(
    name: &str,
    shape: &TypeShape,
    inner: &ConfigNode,
    indent: &str,
    out: &mut String,
) {
    let leaf = leaf_of(inner);
    let getenv =
        |r: &crate::model::EnvRef| format!("std.posix.getenv({})", env_name_literal(&r.name));

    if let Some(kind) = single_kind(shape) {
        let base = zig_kind_type(kind);
        if !shape.has_env {
            let val = match leaf {
                Some(Leaf::Value(v)) => toml_to_zig_literal(v),
                _ => "null".to_string(),
            };
            out.push_str(&format!(
                "{}pub const {}: ?{} = {};\n",
                indent, name, base, val
            ));
            return;
        }
        let (ret, body) = match (shape.nullable, leaf) {
            (true, Some(Leaf::Env(r))) => (format!("?{}", base), getenv(r)),
            (false, Some(Leaf::Env(r))) => (base.to_string(), format!("{}.?", getenv(r))),
            (true, Some(Leaf::Value(v))) => (format!("?{}", base), toml_to_zig_literal(v)),
            (false, Some(Leaf::Value(v))) => (base.to_string(), toml_to_zig_literal(v)),
            _ => (format!("?{}", base), "null".to_string()),
        };
        out.push_str(&format!(
            "{}pub fn {}() {} {{\n{}    return {};\n{}}}\n",
            indent, name, ret, indent, body, indent
        ));
        return;
    }

    let type_name = format!("{}Value", pascal_case(name));
    if !out.ends_with("\n\n") && !out.is_empty() && !out.ends_with("{\n") {
        out.push('\n');
    }
    out.push_str(&format!(
        "{}pub const {} = union(enum) {{\n",
        indent, type_name
    ));
    for k in &shape.kinds {
        out.push_str(&format!(
            "{}    {}: {},\n",
            indent,
            zig_kind_field(*k),
            zig_kind_type(*k)
        ));
    }
    if shape.nullable {
        out.push_str(&format!("{}    none: void,\n", indent));
    }
    out.push_str(&format!("{}}};\n\n", indent));

    let body = match leaf {
        Some(Leaf::Value(v)) => format!(
            "{}{{ .{} = {} }}",
            type_name,
            zig_kind_field(ValueKind::of(v)),
            toml_to_zig_literal(v)
        ),
        Some(Leaf::Env(r)) if shape.nullable => format!(
            "if ({}) |v| {}{{ .str = v }} else {}{{ .none = {{}} }}",
            getenv(r),
            type_name,
            type_name
        ),
        Some(Leaf::Env(r)) => format!("{}{{ .str = {}.? }}", type_name, getenv(r)),
        _ => format!("{}{{ .none = {{}} }}", type_name),
    };
    out.push_str(&format!(
        "{}pub fn {}() {} {{\n{}    return {};\n{}}}\n",
        indent, name, type_name, indent, body, indent
    ));
}

fn pascal_case(name: &str) -> String {
    name.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut c = p.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn sanitize_zig_identifier(name: &str) -> String {
    let is_keyword = matches!(
        name,
        "addrspace"
            | "align"
            | "allowzero"
            | "and"
            | "anyframe"
            | "anytype"
            | "asm"
            | "async"
            | "await"
            | "break"
            | "callconv"
            | "catch"
            | "comptime"
            | "const"
            | "continue"
            | "defer"
            | "else"
            | "enum"
            | "errdefer"
            | "error"
            | "export"
            | "extern"
            | "fn"
            | "for"
            | "if"
            | "inline"
            | "noalias"
            | "noinline"
            | "nosuspend"
            | "opaque"
            | "or"
            | "orelse"
            | "packed"
            | "pub"
            | "resume"
            | "return"
            | "linksection"
            | "struct"
            | "suspend"
            | "switch"
            | "test"
            | "threadlocal"
            | "try"
            | "union"
            | "unreachable"
            | "usingnamespace"
            | "var"
            | "volatile"
            | "while"
            | "null"
            | "true"
            | "false"
    );

    if !is_keyword && is_valid_identifier(name) {
        name.to_string()
    } else {
        format!("@\"{}\"", name)
    }
}

fn toml_to_zig_literal(v: &TomlValue) -> String {
    if let Some(literal) = format_scalar_literal(v) {
        return literal;
    }
    match v {
        TomlValue::Boolean(b) => b.to_string(),
        TomlValue::Array(arr) => {
            if arr.is_empty() {
                "[_][]const u8{}".to_string()
            } else {
                let first = &arr[0];
                let type_prefix = match first {
                    TomlValue::Integer(_) => "[_]i64",
                    TomlValue::Float(_) => "[_]f64",
                    TomlValue::Boolean(_) => "[_]bool",
                    _ => "[_][]const u8",
                };
                let items: Vec<String> = arr.iter().map(toml_to_zig_literal).collect();
                format!("{}{{ {} }}", type_prefix, items.join(", "))
            }
        }
        _ => "\"\"".to_string(),
    }
}
