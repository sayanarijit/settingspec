use super::common::{Leaf, format_scalar_literal, has_env_refs, is_valid_identifier, leaf_of};
use super::tree::{ConfigNode, build_config_tree};
use crate::error::Result;
use crate::model::{EnvFallback, EnvRef, ResolvedSetting, TypeShape, ValueKind};
use indexmap::IndexMap;
use toml::Value as TomlValue;

pub fn generate_python(settings: &[ResolvedSetting]) -> Result<String> {
    let tree = build_config_tree(settings, false);
    let mut out =
        String::from("# Generated by SettingSpec\n\nfrom __future__ import annotations\n\n");
    if has_env_refs(settings) {
        out.push_str("import os\n\n");
    }
    format_python_scope(&tree, 0, &mut out);
    Ok(out)
}

fn format_python_scope(map: &IndexMap<String, ConfigNode>, indent_level: usize, out: &mut String) {
    let indent = "    ".repeat(indent_level);

    if map.is_empty() && indent_level > 0 {
        out.push_str(&format!("{}pass\n", indent));
        return;
    }

    // First write scalar/leaf assignments
    for (k, node) in map {
        match node {
            ConfigNode::Map(_) => {}
            ConfigNode::Typed(shape, inner) => {
                let value = match leaf_of(inner) {
                    Some(Leaf::Value(v)) => toml_to_python_literal(v),
                    Some(Leaf::Env(r)) => env_expression(r),
                    _ => "None".to_string(),
                };
                out.push_str(&format!(
                    "{}{}: {} = {}\n",
                    indent,
                    sanitize_identifier(k),
                    python_type(shape),
                    value
                ));
            }
            ConfigNode::Null | ConfigNode::Env(_) => {
                unreachable!("nulls and environment references are always typed")
            }
            ConfigNode::Value(v) => {
                out.push_str(&format!(
                    "{}{} = {}\n",
                    indent,
                    sanitize_identifier(k),
                    toml_to_python_literal(v)
                ));
            }
        }
    }

    // Then write nested classes
    for (k, node) in map {
        if let ConfigNode::Map(sub_map) = node {
            if indent_level == 0 && !out.ends_with("\n\n") {
                out.push('\n');
            }
            out.push_str(&format!("{}class {}:\n", indent, sanitize_identifier(k)));
            format_python_scope(sub_map, indent_level + 1, out);
            if indent_level == 0 {
                out.push('\n');
            }
        }
    }
}

/// The type hint of a setting: the union of the kinds of its values, and
/// `None` if it is nullable.
fn python_type(shape: &TypeShape) -> String {
    let mut parts: Vec<&str> = shape
        .kinds
        .iter()
        .map(|k| match k {
            ValueKind::String => "str",
            ValueKind::Integer => "int",
            ValueKind::Float => "float",
            ValueKind::Boolean => "bool",
            ValueKind::Array => "list",
            ValueKind::Table => "dict",
        })
        .collect();
    if shape.nullable {
        parts.push("None");
    }
    parts.join(" | ")
}

fn sanitize_identifier(name: &str) -> String {
    if is_valid_identifier(name) {
        name.to_string()
    } else {
        format!(
            "_{}",
            name.replace(|c: char| !c.is_ascii_alphanumeric(), "_")
        )
    }
}

pub(super) fn toml_to_python_literal(v: &TomlValue) -> String {
    if let Some(literal) = format_scalar_literal(v) {
        return literal;
    }
    match v {
        TomlValue::Boolean(b) => {
            if *b {
                "True".to_string()
            } else {
                "False".to_string()
            }
        }
        TomlValue::Array(arr) => {
            let items: Vec<String> = arr.iter().map(toml_to_python_literal).collect();
            format!("[{}]", items.join(", "))
        }
        TomlValue::Table(tbl) => {
            let items: Vec<String> = tbl
                .iter()
                .map(|(k, v)| {
                    format!(
                        "{}: {}",
                        serde_json::to_string(k).unwrap(),
                        toml_to_python_literal(v)
                    )
                })
                .collect();
            format!("{{{}}}", items.join(", "))
        }
        _ => unreachable!("scalars are handled by format_scalar_literal"),
    }
}

pub(super) fn env_expression(r: &EnvRef) -> String {
    let name = serde_json::to_string(&r.name).unwrap();
    match &r.fallback {
        None => format!("os.environ[{}]", name),
        Some(EnvFallback::Null) => format!("os.environ.get({}, None)", name),
        Some(EnvFallback::Value(v)) => {
            format!("os.environ.get({}, {})", name, toml_to_python_literal(v))
        }
    }
}
