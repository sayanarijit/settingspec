use super::common::{
    Leaf, format_scalar_literal, has_env_refs, is_valid_identifier, kind_name, leaf_of, single_kind,
};
use super::tree::{ConfigNode, build_config_tree};
use crate::error::{Result, SettingSpecError};
use crate::model::{ResolvedSetting, TypeShape, ValueKind};
use indexmap::IndexMap;
use toml::Value as TomlValue;

pub fn generate_elm(settings: &[ResolvedSetting]) -> Result<String> {
    // Elm cannot read environment variables, so a reference has no equivalent.
    if has_env_refs(settings) {
        let s = settings
            .iter()
            .find(|s| s.env_ref.is_some())
            .expect("an environment reference has a setting");
        return Err(SettingSpecError::UnresolvedExportUnsupported(
            "elm".to_string(),
            s.key.clone(),
        ));
    }
    let tree = build_config_tree(settings, false);
    let mut types = String::new();
    let mut record = String::new();
    format_elm_record(&tree, 1, "", &mut types, &mut record);
    let out = format!(
        "module Settings exposing (..)\n\n-- Generated by SettingSpec\n\n\n{}settings =\n{}\n",
        types, record
    );
    Ok(out)
}

fn format_elm_record(
    map: &IndexMap<String, ConfigNode>,
    indent_level: usize,
    path: &str,
    types: &mut String,
    out: &mut String,
) {
    let indent = "    ".repeat(indent_level);

    if map.is_empty() {
        out.push_str(&format!("{}{{}}", indent));
        return;
    }

    let mut first = true;
    for (k, node) in map {
        let field_name = sanitize_elm_identifier(k);
        let prefix = if first {
            first = false;
            format!("{}{{ ", indent)
        } else {
            format!("{}, ", indent)
        };

        match node {
            ConfigNode::Typed(shape, inner) => {
                let sum_name = format!("{}{}Value", path, capitalize(k));
                if single_kind(shape).is_none() {
                    types.push_str(&elm_sum_type(&sum_name, shape));
                }
                out.push_str(&format!(
                    "{}{} = {}\n",
                    prefix,
                    field_name,
                    elm_typed_value(shape, &sum_name, inner)
                ));
            }
            ConfigNode::Null | ConfigNode::Env(_) => {
                unreachable!("nulls and environment references are always typed")
            }
            ConfigNode::Value(v) => match v {
                TomlValue::Table(tbl) => {
                    let mut sub_map = IndexMap::new();
                    for (sub_k, sub_v) in tbl {
                        sub_map.insert(sub_k.clone(), ConfigNode::Value(sub_v.clone()));
                    }
                    out.push_str(&format!("{}{} =\n", prefix, field_name));
                    format_elm_record(
                        &sub_map,
                        indent_level + 1,
                        &format!("{}{}", path, capitalize(k)),
                        types,
                        out,
                    );
                    out.push('\n');
                }
                _ => {
                    out.push_str(&format!(
                        "{}{} = {}\n",
                        prefix,
                        field_name,
                        toml_to_elm_literal(v)
                    ));
                }
            },
            ConfigNode::Map(sub_map) => {
                out.push_str(&format!("{}{} =\n", prefix, field_name));
                format_elm_record(
                    sub_map,
                    indent_level + 1,
                    &format!("{}{}", path, capitalize(k)),
                    types,
                    out,
                );
                out.push('\n');
            }
        }
    }
    out.push_str(&format!("{}}}", indent));
}

fn elm_kind_type(kind: ValueKind) -> &'static str {
    match kind {
        ValueKind::String => "String",
        ValueKind::Integer => "Int",
        ValueKind::Float => "Float",
        ValueKind::Boolean => "Bool",
        ValueKind::Array | ValueKind::Table => unreachable!("rejected before formatting"),
    }
}

/// `type` declaration of the custom type of a setting with several kinds.
fn elm_sum_type(name: &str, shape: &TypeShape) -> String {
    let mut ctors: Vec<String> = shape
        .kinds
        .iter()
        .map(|k| format!("{}{} {}", name, kind_name(*k), elm_kind_type(*k)))
        .collect();
    if shape.nullable {
        ctors.push(format!("{}Null", name));
    }
    format!("type {}\n    = {}\n\n\n", name, ctors.join("\n    | "))
}

fn elm_typed_value(shape: &TypeShape, sum_name: &str, inner: &ConfigNode) -> String {
    let single = single_kind(shape).is_some();
    match leaf_of(inner) {
        Some(Leaf::Value(v)) => {
            let lit = toml_to_elm_literal(v);
            if single && shape.nullable {
                format!("Just ({})", lit)
            } else if single {
                lit
            } else {
                format!("{}{} ({})", sum_name, kind_name(ValueKind::of(v)), lit)
            }
        }
        _ if single => "Nothing".to_string(),
        _ => format!("{}Null", sum_name),
    }
}

fn sanitize_elm_identifier(name: &str) -> String {
    let is_keyword = matches!(
        name,
        "if" | "then"
            | "else"
            | "case"
            | "of"
            | "let"
            | "in"
            | "type"
            | "module"
            | "where"
            | "import"
            | "exposing"
            | "as"
            | "port"
    );

    if is_keyword {
        format!("{}_", name)
    } else if is_valid_identifier(name) && name.chars().next().unwrap().is_ascii_lowercase() {
        name.to_string()
    } else {
        let clean = name.replace(|c: char| !c.is_ascii_alphanumeric(), "_");
        let mut chars = clean.chars();
        match chars.next() {
            None => "setting".to_string(),
            Some(first) => {
                if first.is_ascii_digit() || first == '_' {
                    format!("k_{}", clean)
                } else {
                    format!("{}{}", first.to_ascii_lowercase(), chars.as_str())
                }
            }
        }
    }
}

fn toml_to_elm_literal(v: &TomlValue) -> String {
    if let Some(literal) = format_scalar_literal(v) {
        return literal;
    }
    match v {
        TomlValue::Boolean(b) => {
            if *b {
                "True".to_string()
            } else {
                "False".to_string()
            }
        }
        TomlValue::Array(arr) => {
            let items: Vec<String> = arr.iter().map(toml_to_elm_literal).collect();
            format!("[ {} ]", items.join(", "))
        }
        _ => "\"\"".to_string(),
    }
}

/// Capitalizes `s` and replaces characters that are invalid in a type name.
fn capitalize(s: &str) -> String {
    let clean = s.replace(|c: char| !c.is_ascii_alphanumeric(), "_");
    let mut c = clean.chars();
    match c.next() {
        None => String::new(),
        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
    }
}
