use super::common::{
    Leaf, env_name_literal, format_scalar_literal, is_valid_identifier, leaf_of, single_kind,
};
use super::tree::{ConfigNode, build_config_tree};
use crate::error::Result;
use crate::model::{ResolvedSetting, TypeShape, ValueKind};
use indexmap::IndexMap;
use toml::Value as TomlValue;

pub fn generate_scala(settings: &[ResolvedSetting]) -> Result<String> {
    let tree = build_config_tree(settings, false);
    let mut out = String::from("// Generated by SettingSpec\n\nobject Settings {\n");
    format_scala_scope(&tree, 1, &mut out);
    out.push_str("}\n");
    Ok(out)
}

fn format_scala_scope(map: &IndexMap<String, ConfigNode>, indent_level: usize, out: &mut String) {
    let indent = "  ".repeat(indent_level);

    // Leaf/scalar constants first
    for (k, node) in map {
        let field_name = sanitize_scala_identifier(k);
        match node {
            ConfigNode::Typed(shape, inner) => {
                let (type_str, val_str) = scala_typed(shape, inner);
                let modifier = if shape.has_env {
                    "lazy val"
                } else {
                    "final val"
                };
                out.push_str(&format!(
                    "{}{} {}: {} = {}\n",
                    indent, modifier, field_name, type_str, val_str
                ));
            }
            ConfigNode::Null | ConfigNode::Env(_) => {
                unreachable!("nulls and environment references are always typed")
            }
            ConfigNode::Value(v) => match v {
                TomlValue::Table(_) => {} // Handled in object loop below
                TomlValue::Boolean(b) => {
                    out.push_str(&format!(
                        "{}final val {}: Boolean = {}\n",
                        indent, field_name, b
                    ));
                }
                TomlValue::Array(arr) => {
                    let (type_str, val_str) = scala_array_literal(arr);
                    out.push_str(&format!(
                        "{}val {}: {} = {}\n",
                        indent, field_name, type_str, val_str
                    ));
                }
                _ => {
                    let (type_str, val_str) = toml_to_scala_const(v);
                    out.push_str(&format!(
                        "{}final val {}: {} = {}\n",
                        indent, field_name, type_str, val_str
                    ));
                }
            },
            ConfigNode::Map(_) => {}
        }
    }

    // Nested singleton objects next
    for (k, node) in map {
        let obj_name = sanitize_scala_identifier(k);
        match node {
            ConfigNode::Map(sub_map) => {
                if !out.ends_with("\n\n") && !out.ends_with("{\n") {
                    out.push('\n');
                }
                out.push_str(&format!("{}object {} {{\n", indent, obj_name));
                format_scala_scope(sub_map, indent_level + 1, out);
                out.push_str(&format!("{}}}\n", indent));
            }
            ConfigNode::Value(TomlValue::Table(tbl)) => {
                if !out.ends_with("\n\n") && !out.ends_with("{\n") {
                    out.push('\n');
                }
                out.push_str(&format!("{}object {} {{\n", indent, obj_name));
                let mut sub_map = IndexMap::new();
                for (sub_k, sub_v) in tbl {
                    sub_map.insert(sub_k.clone(), ConfigNode::Value(sub_v.clone()));
                }
                format_scala_scope(&sub_map, indent_level + 1, out);
                out.push_str(&format!("{}}}\n", indent));
            }
            _ => {}
        }
    }
}

fn sanitize_scala_identifier(name: &str) -> String {
    let is_keyword = matches!(
        name,
        "abstract"
            | "case"
            | "catch"
            | "class"
            | "def"
            | "do"
            | "else"
            | "extends"
            | "false"
            | "final"
            | "finally"
            | "for"
            | "forSome"
            | "if"
            | "implicit"
            | "import"
            | "lazy"
            | "match"
            | "new"
            | "null"
            | "object"
            | "override"
            | "package"
            | "private"
            | "protected"
            | "return"
            | "sealed"
            | "super"
            | "this"
            | "throw"
            | "trait"
            | "try"
            | "true"
            | "type"
            | "val"
            | "var"
            | "while"
            | "with"
            | "yield"
    );

    if is_keyword {
        format!("`{}`", name)
    } else if is_valid_identifier(name) {
        name.to_string()
    } else {
        format!(
            "_{}",
            name.replace(|c: char| !c.is_ascii_alphanumeric(), "_")
        )
    }
}

/// The Scala type and value expression of a value whose type is shared by all
/// profiles: `T` for a single scalar kind, otherwise `Any`, wrapped in
/// `Option` if the setting is nullable.
fn scala_typed(shape: &TypeShape, inner: &ConfigNode) -> (String, String) {
    let scalar = single_kind(shape).and_then(|k| match k {
        ValueKind::String => Some("String"),
        ValueKind::Integer => Some("Long"),
        ValueKind::Float => Some("Double"),
        ValueKind::Boolean => Some("Boolean"),
        ValueKind::Array | ValueKind::Table => None,
    });
    let base = scalar.unwrap_or("Any");
    let type_str = if shape.nullable {
        format!("Option[{}]", base)
    } else {
        base.to_string()
    };

    let value = match leaf_of(inner) {
        Some(Leaf::Value(v)) => {
            let lit = match v {
                TomlValue::Array(arr) => scala_array_literal(arr).1,
                _ => toml_to_scala_const(v).1,
            };
            if shape.nullable {
                format!("Some({})", lit)
            } else {
                lit
            }
        }
        Some(Leaf::Env(r)) => {
            let name = env_name_literal(&r.name);
            if shape.nullable {
                format!("sys.env.get({})", name)
            } else {
                format!("sys.env({})", name)
            }
        }
        _ => "None".to_string(),
    };
    (type_str, value)
}

fn toml_to_scala_const(v: &TomlValue) -> (&'static str, String) {
    if let Some(literal) = format_scalar_literal(v) {
        match v {
            TomlValue::String(_) | TomlValue::Datetime(_) => ("String", literal),
            TomlValue::Integer(_) => ("Long", format!("{}L", literal)),
            TomlValue::Float(_) => ("Double", literal),
            _ => unreachable!(),
        }
    } else {
        match v {
            TomlValue::Boolean(b) => ("Boolean", b.to_string()),
            _ => ("String", "\"\"".to_string()),
        }
    }
}

fn scala_array_literal(arr: &[TomlValue]) -> (&'static str, String) {
    if arr.is_empty() {
        return ("List[String]", "List.empty[String]".to_string());
    }
    let first = &arr[0];
    let (_elem_type, list_type) = match first {
        TomlValue::Integer(_) => ("Long", "List[Long]"),
        TomlValue::Float(_) => ("Double", "List[Double]"),
        TomlValue::Boolean(_) => ("Boolean", "List[Boolean]"),
        _ => ("String", "List[String]"),
    };
    let items: Vec<String> = arr
        .iter()
        .map(|item| match item {
            TomlValue::Integer(i) => format!("{}L", i),
            TomlValue::Boolean(b) => b.to_string(),
            _ => format_scalar_literal(item).unwrap_or_else(|| "\"\"".to_string()),
        })
        .collect();
    (list_type, format!("List({})", items.join(", ")))
}
