use super::common::is_valid_identifier;
use super::javascript::{generate_js_object, process_env};
use super::tree::{ConfigNode, build_config_tree};
use crate::error::Result;
use crate::model::{EnvRef, ResolvedSetting, TypeShape, ValueKind};
use indexmap::IndexMap;
use toml::Value as TomlValue;

pub fn generate_typescript(settings: &[ResolvedSetting]) -> Result<String> {
    let tree = build_config_tree(settings, false);
    let mut interfaces = String::new();
    let root_type = generate_ts_interfaces(&tree, "Settings", &mut interfaces);

    let json_val = generate_js_object(settings, env_expression)?;
    let mut out = String::new();
    out.push_str("// Generated by SettingSpec\n\n");
    out.push_str(&interfaces);
    out.push_str(&format!(
        "\nconst settings: {} = {};\n\nexport default settings;\n",
        root_type, json_val
    ));
    Ok(out)
}

fn generate_ts_interfaces(
    map: &IndexMap<String, ConfigNode>,
    interface_name: &str,
    out: &mut String,
) -> String {
    let mut fields = Vec::new();

    for (k, node) in map {
        match node {
            ConfigNode::Typed(shape, _) => {
                fields.push(format!(
                    "  {}: {};",
                    sanitize_ts_key(k),
                    ts_union_type(shape)
                ));
            }
            ConfigNode::Null | ConfigNode::Env(_) => {
                unreachable!("nulls and environment references are always typed")
            }
            ConfigNode::Value(v) => {
                fields.push(format!("  {}: {};", sanitize_ts_key(k), ts_type_of(v)));
            }
            ConfigNode::Map(sub_map) => {
                let sub_name = format!("{}{}", interface_name, capitalize(k));
                let sub_type = generate_ts_interfaces(sub_map, &sub_name, out);
                fields.push(format!("  {}: {};", sanitize_ts_key(k), sub_type));
            }
        }
    }

    let iface = format!(
        "export interface {} {{\n{}\n}}\n",
        interface_name,
        fields.join("\n")
    );
    out.push_str(&iface);
    interface_name.to_string()
}

fn sanitize_ts_key(key: &str) -> String {
    if is_valid_identifier(key) {
        key.to_string()
    } else {
        format!("\"{}\"", key)
    }
}

fn capitalize(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        None => String::new(),
        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
    }
}

fn ts_type_of(v: &TomlValue) -> &'static str {
    match v {
        TomlValue::String(_) | TomlValue::Datetime(_) => "string",
        TomlValue::Integer(_) | TomlValue::Float(_) => "number",
        TomlValue::Boolean(_) => "boolean",
        TomlValue::Array(_) => "any[]",
        TomlValue::Table(_) => "Record<string, any>",
    }
}

/// `process.env.NAME`, which is `string | undefined`; cast when the setting
/// is not nullable.
fn env_expression(r: &EnvRef, nullable: bool) -> String {
    let access = process_env(&r.name);
    if nullable {
        format!("({} ?? null)", access)
    } else {
        format!("{} as string", access)
    }
}

/// The union of the kinds of the shape, plus `null` if it is nullable.
fn ts_union_type(shape: &TypeShape) -> String {
    let mut parts: Vec<&str> = Vec::new();
    for kind in &shape.kinds {
        let name = match kind {
            ValueKind::String => "string",
            ValueKind::Integer | ValueKind::Float => "number",
            ValueKind::Boolean => "boolean",
            ValueKind::Array => "any[]",
            ValueKind::Table => "Record<string, any>",
        };
        if !parts.contains(&name) {
            parts.push(name);
        }
    }
    if shape.nullable {
        parts.push("null");
    }
    parts.join(" | ")
}
